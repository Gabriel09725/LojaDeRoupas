    private void carregarProdutosTabela() {
        String categoriaSelecionada = cbProduto.getSelectedItem() != null ? cbProduto.getSelectedItem().toString() : "";
        DAO.ProdutoDAO dao = new DAO.ProdutoDAO();
        produtosDisponiveis = dao.buscarPorCategoria(categoriaSelecionada);
        DefaultTableModel model = (DefaultTableModel) tabelaItens.getModel();
        model.setRowCount(0);
        if (produtosDisponiveis != null) {
            for (Produto p : produtosDisponiveis) {
                model.addRow(new Object[]{
                    p.getId(),
                    p.getNome(),
                    p.getCategoria(),
                    p.getTamanho(),
                    p.getCor(),
                    p.getEstoque(),
                    String.format("R$ %.2f", p.getPreco())
                });
            }
        }
    }

