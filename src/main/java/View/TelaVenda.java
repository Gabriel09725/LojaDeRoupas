    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        // TODO add your handling code here:
        int linhaSelecionada = tabelaItens.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma peça na tabela para adicionar!", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String qtdStr = txtQuantidade.getText().trim();
        if (qtdStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe a quantidade do produto!", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            int quantidade = Integer.parseInt(qtdStr);
            if (quantidade <= 0) {
                JOptionPane.showMessageDialog(this, "A quantidade deve ser maior que zero!", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }
            Object precoObj = tabelaItens.getValueAt(linhaSelecionada, 6);
            String strPreco = precoObj.toString().replace("R$", "").replace(",", ".").trim();
            double precoUnitario = Double.parseDouble(strPreco);
            double subtotal = precoUnitario * quantidade;
            totalPagar += subtotal;
            atualizarTotalLabel();
            txtQuantidade.setText("1");
            JOptionPane.showMessageDialog(this, "Item adicionado! Total acumulado atualizado.");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Quantidade inválida!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
        if (totalPagar <= 0) {
            JOptionPane.showMessageDialog(this, "Adicione pelo menos um item para finalizar a venda!");
            return;
        }
        TelaPagamento telaPagamento = new TelaPagamento(totalPagar);
        telaPagamento.setLocationRelativeTo(null);
        telaPagamento.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_btnFinalizarActionPerformed

